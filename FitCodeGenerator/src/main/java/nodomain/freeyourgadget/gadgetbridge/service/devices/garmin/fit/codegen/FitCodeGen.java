    private static void writeJSon(final Writer writer, final SortedSet<FitMessage> messages,
                                  final SortedSet<FitEnum> enums, final SortedSet<FitDevice> devices) throws IOException {
        try (JsonWriter o = new JsonWriter(writer)) {
            o.setSerializeNulls(true);
            o.setIndent("  ");
            o.beginObject();

            o.name("messages");
            o.beginArray();
            for (final FitMessage m : messages) {
                o.beginObject();
                o.name("num").value(m.num);
                o.name("name").value(m.name);
                o.name("fields");
                o.beginArray();
                for (final FitField field : m.getFieldDefinitionPrimitives()) {
                    printJSon(field, o);
                }
                o.endArray();
                o.endObject();
            }
            o.endArray();

            o.name("enumerations");
            o.beginArray();
            for (final FitEnum fitEnum : enums) {
                o.beginObject();
                o.name("name").value(fitEnum.name);
                o.name("entries");
                o.beginArray();
                for (final FitEnumEntry fitEnumEntry : fitEnum.entries) {
                    o.beginObject();
                    o.setFormattingStyle(FormattingStyle.COMPACT);
                    o.name("num").value(fitEnumEntry.num);
                    o.name("name").value(fitEnumEntry.name);
                    if (fitEnumEntry.label != null) {
                        o.name("label").value(fitEnumEntry.label);
                    }
                    if (fitEnumEntry.text != null) {
                        o.name("text").value(fitEnumEntry.text);
                    }
                    o.endObject();
                    o.setFormattingStyle(FormattingStyle.PRETTY);
                }
                o.endArray();
                o.endObject();
            }
            o.endArray();

            o.name("devices");
            o.beginArray();
            for (final FitDevice fitDevice : devices) {
                o.beginObject();
                o.setFormattingStyle(FormattingStyle.COMPACT);
                o.name("manufacturer").value(fitDevice.manufacturer);
                o.name("product").value(fitDevice.product);
                o.name("name").value(fitDevice.name);
                o.endObject();
                o.setFormattingStyle(FormattingStyle.PRETTY);
            }
            o.endArray();

            o.endObject();
        }
    }

    private static void printJSon(final FitField f, final JsonWriter o) throws IOException {
        o.beginObject();
        o.setFormattingStyle(FormattingStyle.COMPACT);
        o.name("num").value(f.num);
        o.name("name").value(f.name);
        o.name("base").value(f.base);
        if (1 != f.scale) {
            o.name("scale");
            long l = Math.round(f.scale);
            if (l == f.scale) {
                o.value(l);
            } else {
                o.value(f.scale);
            }
        }
        if (f.type != null && !"ARRAY".contentEquals(f.type)) {
            o.name("type").value(f.type);
        }
        if (0 != f.offset) {
            o.name("offset");
            long l = Math.round(f.offset);
            if (l == f.offset) {
                o.value(l);
            } else {
                o.value(f.offset);
            }
        }
        if (f.arrayLen >= 0) {
            o.name("arrayLen").value(f.arrayLen);
        }
        if (f.stringLen >= 0) {
            o.name("stringLen").value(f.stringLen);
        }
        if (f.UOM != null) {
            o.name("UOM").value(f.UOM);
        }
        o.endObject();
        o.setFormattingStyle(FormattingStyle.PRETTY);
    }

    static class FitField implements Comparable<FitField> {
        int num;
        String name;
        String type;
        String base;
        double scale;
        double offset;
        int arrayLen;
        int stringLen;
        String UOM;

        FitField() {
            scale = 1;
            offset = 0;
            arrayLen = -1;
            stringLen = -1;
        }

        @Override
        public int compareTo(final FitField o) {
            return Integer.compare(num, o.num);
        }

        String getName() {
            return name;
        }

        String getType() {
            return type;
        }

        String getBase() {
            return base;
        }

        int getNumber() {
            return num;
        }

        double getScale() {
            return scale;
        }
    }

