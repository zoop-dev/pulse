    public static void main(final String[] args) throws Exception {
        final long startTime = System.currentTimeMillis();

        final String pathToJson = (args.length > 0) ? args[0] : "FitCodeGenerator/src/main/resources/fit_profile.json";
        final String pathToOutput = (args.length > 1) ? args[1] : "app/build/generated/sources/fit/nodomain/freeyourgadget/gadgetbridge/service/devices/garmin/fit/";
        final String pathToManual = (args.length > 2) ? args[2] : "app/src/main/java/nodomain/freeyourgadget/gadgetbridge/service/devices/garmin/fit/";

        final File jsonFile = new File(pathToJson).getAbsoluteFile();
        final File outputDir = new File(pathToOutput).getAbsoluteFile();

        final SortedSet<FitMessage> messages = new TreeSet<>();
        final SortedSet<FitEnum> enumerations = new TreeSet<>();
        final SortedSet<FitDevice> devices = new TreeSet<>();
        try (final FileReader reader = new FileReader(jsonFile, StandardCharsets.UTF_8)) {
            readJson(reader, messages, enumerations, devices);
        }

        if (false) {
            // only used for mass updates to fit_profile.json
            //modifyProfile(messages, enumerations);
            try (Writer writer = new FileWriter(jsonFile, StandardCharsets.UTF_8)) {
                writeJSon(writer, messages, enumerations, devices);
            }
        }

        final File messagesTarget = new File(outputDir, "messages").getAbsoluteFile();
        final File messagesManual = new File(pathToManual, "messages").getAbsoluteFile();

        final File enumsTarget = new File(outputDir, "enums").getAbsoluteFile();

        final File fieldTarget = new File(outputDir, "fieldDefinitions").getAbsoluteFile();
        final File fieldManual = new File(pathToManual, "fieldDefinitions").getAbsoluteFile();

        prepareTargetFolder(messagesTarget);
        prepareTargetFolder(enumsTarget);
        prepareTargetFolder(fieldTarget);

        generateNativeFile(messages, outputDir);
        generateFitRecordDataFactory(messages, messagesTarget);
        for (final FitMessage message : messages) {
            generateFitMessageClassFile(message, messagesTarget, messagesManual);
        }
        for (final FitEnum enumeration : enumerations) {
            generateFitEnumFile(enumeration, enumsTarget);
            generateFitEnumFieldDefinitionFile(enumeration, fieldTarget, fieldManual);
        }
        generateFitFieldDefinitionsFile(enumerations, fieldTarget);

        final long time = System.currentTimeMillis() - startTime;
        System.out.println("Written " + FILE_WRITTEN_COUNTER + " files to " + outputDir + " in " + time + "ms");
    }

    private static void generateFitEnumFieldDefinitionFile(final FitEnum enumeration,
                                                           final File fieldTarget,
                                                           final File fieldManual) throws IOException {
        final File manualFile = new File(fieldManual, "FieldDefinition" + enumeration.name + ".java");
        if (manualFile.exists()) {
            // a manualy defined FieldDefinition exists
            return;
        }

        final String output = FIELD_DEFINTION
                .replace("${copyrightHeader}", COPYRIGHT_HEADER)
                .replace("${autoGenerated}", AUTO_GENRATED)
                .replace("${enumType}", enumeration.name);

        final File fieldDefinitionFile = new File(fieldTarget, "FieldDefinition" + enumeration.name + ".java");
        Files.writeString(fieldDefinitionFile.toPath(), output, StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.CREATE);
        fileWritten(fieldDefinitionFile);
    }

    private static void fileWritten(final File outputFile) throws IOException {
        if (Boolean.getBoolean("verbose")) {
            System.out.println("Written " + outputFile.getCanonicalPath());
        }
        FILE_WRITTEN_COUNTER++;
    }

    private static void generateFitFieldDefinitionsFile(final Iterable<FitEnum> enumerations,
                                                        final File fieldTarget) throws IOException {
        final StringBuilder builder = new StringBuilder(FIELD_DEFINITIONS
                .replace("${copyrightHeader}", COPYRIGHT_HEADER)
                .replace("${autoGenerated}", AUTO_GENRATED)
        );
        for (final FitEnum fitEnum : enumerations) {
            builder.append("    ");
            builder.append(fitEnum.name);
            builder.append(",\n");
        }
        builder.append("    ;\n");
        builder.append("    public static FieldDefinition create(int localNumber, int size, FieldDefinitions field, BaseType baseType, String name, int scale, int offset) {\n");
        builder.append("        return switch(field) {\n");
        for (final FitEnum fitEnum : enumerations) {
            builder.append(ENUM_CREATION.replace("${enumType}", fitEnum.name));
        }
        builder.append("            default -> throw new UnsupportedOperationException(field.toString());\n");
        builder.append("        };\n");
        builder.append("    }\n");
        builder.append("}\n");

        final File outputFile = new File(fieldTarget, "FieldDefinitions.java");
        Files.writeString(outputFile.toPath(), builder.toString(), StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.CREATE);
        fileWritten(outputFile);
    }

